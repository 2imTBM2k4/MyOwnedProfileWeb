import assert from 'node:assert/strict';
import { Browser, sleep } from 'file:///C:/Users/Silentboiz/.codex/plugins/cache/claude-sync/taste-skill/2.1.4/skills/taste-skill/scripts/lib/cdp.mjs';
const b = await Browser.launch();
try {
  const p = await b.newPage({ width: 1440, height: 900 });
  await p.goto('http://127.0.0.1:3100', { settleMs: 1700 });
  assert.equal(await p.eval(() => document.documentElement.classList.contains('lenis')), true, 'smooth scroll is mounted');
  await p.send('Input.dispatchMouseEvent', { type: 'mouseWheel', x: 720, y: 450, deltaY: 650, deltaX: 0 });
  await sleep(80);
  const early = await p.eval(() => scrollY);
  await sleep(900);
  const late = await p.eval(() => scrollY);
  assert.ok(early > 0 && early < late && late > 600, `wheel inertia ${early} -> ${late}`);
  assert.equal(await p.eval(() => document.querySelector('header').dataset.compact), 'true');
  await p.eval(() => document.querySelector('nav a[href="#about"]').click());
  await sleep(1300);
  const headingTop = await p.eval(() => document.querySelector('#about h2').getBoundingClientRect().top);
  assert.ok(Math.abs(headingTop - 112) < 4, `one navbar offset only, heading at ${headingTop}`);
  await p.eval(() => document.querySelector('nav a[href="#contact"]').click());
  await sleep(1400);
  assert.equal(await p.eval(() => location.hash), '#contact');
  assert.equal(await p.eval(() => document.querySelector('nav a[href="#contact"]').getAttribute('aria-current')), 'location');
  await p.screenshot({ path: '.taste-skill/profile-refresh/footer-desktop.jpg' });
  const footer = await p.eval(() => ({ stage: document.querySelector('footer').getBoundingClientRect().toJSON(), panel: document.querySelector('footer > div').getBoundingClientRect().toJSON(), position: getComputedStyle(document.querySelector('footer > div')).position }));
  assert.equal(footer.position, 'fixed');
  assert.ok(footer.panel.top >= 100 && footer.panel.bottom <= 901);
  await p.eval(() => document.querySelector('footer a[href="#hero"]').click());
  await sleep(1400);
  assert.ok(await p.eval(() => scrollY < 5));
  assert.equal(await p.eval(() => document.querySelector('header').dataset.compact), 'false');
  await p.send('Input.dispatchMouseEvent', { type: 'mouseWheel', x: 720, y: 450, deltaY: 550, deltaX: 0 });
  await sleep(40);
  await p.eval(() => document.querySelector('footer a[href^="mailto:"]').focus());
  await sleep(650);
  assert.ok(await p.eval(() => document.querySelector('footer').getBoundingClientRect().bottom <= innerHeight + 2), 'keyboard focus brings footer into view');
  await p.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  await sleep(100);
  assert.equal(await p.eval(() => document.documentElement.classList.contains('lenis')), false, 'live reduced motion destroys smoother');
  await p.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] });
  await sleep(100);
  assert.equal(await p.eval(() => document.documentElement.classList.contains('lenis')), true, 'live preference restores smoother');
  await p.setViewport({ width: 1440, height: 650 });
  assert.equal(await p.eval(() => getComputedStyle(document.querySelector('footer > div')).position), 'static', 'short screens keep all footer content in normal flow');
  const reduced = await b.newPage({ width: 390, height: 844, reducedMotion: true });
  await reduced.goto('http://127.0.0.1:3100');
  assert.equal(await reduced.eval(() => document.documentElement.classList.contains('lenis')), false);
  assert.equal(await reduced.eval(() => getComputedStyle(document.querySelector('footer > div')).position), 'static');
  await reduced.eval(() => document.querySelector('nav a[href="#contact"]').click());
  await sleep(250);
  assert.equal(await reduced.eval(() => location.hash), '#contact');
  assert.ok(await reduced.eval(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(p.consoleErrors, []);
  assert.deepEqual(reduced.consoleErrors, []);
  console.log('PASS: wheel inertia, compact navbar, active links/hash, footer reveal, return-to-top, keyboard focus, reduced motion/mobile');
} finally { await b.close(); }
